async function uploadAll() {
  console.log('🚀 고품질 공략 100개 업로드 시작 (1차 25개)...\n');
  const existing = await db.collection('guides').get();
  console.log(`기존 공략: ${existing.size}개\n`);
  let ok = 0, fail = 0;
  for (const g of GUIDES) {
    try {
      await db.collection('guides').add({ ...g, createdAt: new Date().toISOString() });
      console.log(`  ✅ ${g.game} — ${g.title.substring(0,40)}...`);
      ok++;
    } catch(e) {
      console.log(`  ❌ 실패: ${e.message}`);
      fail++;
    }
  }
  console.log(`\n✅ 완료! 성공 ${ok}개 / 실패 ${fail}개`);
  const after = await db.collection('guides').get();
  console.log(`총 공략: ${after.size}개`);
  process.exit(0);
}
uploadAll().catch(console.error);
